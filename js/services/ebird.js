/**
 * Resolves the 4-6 letter eBird species code from a bird object, common name, or scientific name.
 */
export function getEbirdSpeciesCode(speciesOrName, scientificName = "") {
  if (!speciesOrName) return null;

  let common = "";
  let sci = "";

  if (typeof speciesOrName === "object" && speciesOrName !== null) {
    common = String(speciesOrName.common_name || "").trim().toLowerCase();
    sci = String(speciesOrName.scientific_name || "").trim().toLowerCase();
  } else if (typeof speciesOrName === "string") {
    common = speciesOrName.trim().toLowerCase();
    sci = String(scientificName || "").trim().toLowerCase();
  }

  // 1. Direct scientific name lookup (most canonical)
  if (sci && EBIRD_SPECIES_CODES[sci]) {
    return EBIRD_SPECIES_CODES[sci];
  }

  // 2. Direct common name lookup
  if (common && EBIRD_SPECIES_CODES[common]) {
    return EBIRD_SPECIES_CODES[common];
  }

  // 3. Normalized stripped variations (e.g. without hyphens or single quotes)
  const normCommon = common.replace(/['’]/g, "").replace(/-/g, " ");
  if (EBIRD_SPECIES_CODES[normCommon]) {
    return EBIRD_SPECIES_CODES[normCommon];
  }

  return null;
}

/**
 * Returns the destination URL for a given species on eBird.
 * Falls back to an eBird search redirect if the species code is not yet mapped.
 */
export function getEbirdUrl(speciesOrName, scientificName = "") {
  const code = getEbirdSpeciesCode(speciesOrName, scientificName);
  if (code) {
    return `https://ebird.org/species/${code}`;
  }

  const queryName = typeof speciesOrName === "object" && speciesOrName !== null
    ? speciesOrName.common_name || speciesOrName.scientific_name || ""
    : speciesOrName || scientificName || "";

  if (!queryName) {
    return "https://ebird.org/explore";
  }

  // Search redirect directly targeting eBird's species profiles
  return `https://www.google.com/search?q=site:ebird.org/species+${encodeURIComponent(queryName)}`;
}

/**
 * Creates a styled external eBird link element.
 */
export function createEbirdLink(species, {
  label = "eBird",
  compact = false,
  className = "",
} = {}) {
  const commonName = typeof species === "object" && species !== null
    ? species.common_name || species.name || "Bird"
    : species;
  const url = getEbirdUrl(species);

  const link = document.createElement("a");
  link.href = url;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  link.className = compact
    ? `ebird-link ebird-link--compact ${className}`.trim()
    : `ebird-link ${className}`.trim();
  link.title = `Explore ${commonName} on eBird (opens in new tab)`;

  link.innerHTML = `<span>${label}</span> <span class="ebird-arrow" aria-hidden="true">↗</span>`;

  return link;
}
